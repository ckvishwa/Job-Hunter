"""Independent-oracle tests: tests/fixtures/resume_cases.json holds hand-authored resume content AND the expected facts,
written from the resume text, not generated by the parser. Each case is built into a real PDF or DOCX and sent through the
real HTTP contract."""
from __future__ import annotations

import hashlib
import json
from pathlib import Path

import pytest
from fastapi.testclient import TestClient

from app.contracts import FORBIDDEN_KINDS, ExtractResponse
from app.main import Settings, create_app
from app.qwen_fallback import QwenFallback
from tests.builders import build

TOKEN = "t" * 40
CASES = json.loads((Path(__file__).parent / "fixtures" / "resume_cases.json").read_text(encoding="utf-8"))


@pytest.fixture(scope="module")
def client() -> TestClient:
    settings = Settings(service_token=TOKEN, qwen=QwenFallback(False, "http://127.0.0.1:11434", "qwen2.5:3b-instruct-q4_K_M"))
    return TestClient(create_app(settings))


def utf16_slice(text: str, start: int, end: int) -> str:
    return text.encode("utf-16-le")[2 * start: 2 * end].decode("utf-16-le")


def post(client: TestClient, data: bytes, file_type: str, token: str = TOKEN):
    return client.post(f"/internal/v1/ai/extract-resume?fileType={file_type}", content=data,
                       headers={"authorization": f"Bearer {token}", "content-type": "application/octet-stream"})


def normalized(attrs: dict) -> dict:
    return {k: v for k, v in attrs.items() if v is not None}


def test_there_are_at_least_ten_independent_cases_in_both_formats():
    assert len(CASES) >= 10
    assert {c["format"] for c in CASES} == {"pdf", "docx"}
    assert len({c["id"] for c in CASES}) == len(CASES)


@pytest.mark.parametrize("case", CASES, ids=[c["id"] for c in CASES])
def test_case_matches_hand_authored_expectation(client: TestClient, case: dict):
    data = build(case["format"], case["lines"], blank_pages=case.get("blankPages", 0))
    response = post(client, data, case["format"])
    expected = case["expected"]

    if "error" in expected:
        assert response.status_code == 422
        assert response.json()["error"]["code"] == expected["error"]
        return

    assert response.status_code == 200, response.text
    body = ExtractResponse.model_validate(response.json())  # strict contract, extra fields rejected
    assert body.textSha256 == hashlib.sha256(body.text.encode("utf-8")).hexdigest()

    got = [(f.kind, f.value, normalized(f.attributes.model_dump())) for f in body.facts]
    want = [(f["kind"], f["value"], f.get("attributes", {})) for f in expected["facts"]]
    # Exact multiset equality: a missing fact AND an extra (possibly fabricated) fact both fail.
    key = lambda t: (t[0], t[1], json.dumps(t[2], sort_keys=True))
    assert sorted(got, key=key) == sorted(want, key=key)
    assert sorted(w.code for w in body.warnings) == sorted(expected["warningCodes"])

    for fact in body.facts:
        assert fact.kind not in FORBIDDEN_KINDS
        assert fact.proposedBy == "rules"
        # The quote is exactly the text at the reported UTF-16 span (what JavaScript's String.slice will see).
        assert utf16_slice(body.text, fact.span.start, fact.span.end) == fact.span.quote
        assert 0 <= fact.span.start < fact.span.end <= len(body.text.encode("utf-16-le")) // 2
